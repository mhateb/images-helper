import { describe, expect, it } from 'vitest';
import { isPrivateIp } from '../src/analyzePage.js';

describe('isPrivateIp', () => {
  it.each([
    '10.0.0.1',
    '127.0.0.1',
    '0.0.0.0',
    '169.254.1.1',
    '172.16.0.1',
    '172.31.255.255',
    '192.168.1.20',
    '100.64.0.1',
    '100.127.255.255',
    '224.0.0.1',
    '240.0.0.1',
    '255.255.255.255',
    '::',
    '::1',
    'fc00::1',
    'fd12:3456::1',
    'fe80::1',
    'ff02::1',
    '::ffff:127.0.0.1',
    '::ffff:10.1.2.3',
    '::FFFF:192.168.0.10',
    'not-an-ip',
  ])('считает %s внутренним', (ip) => {
    expect(isPrivateIp(ip)).toBe(true);
  });

  it.each([
    '8.8.8.8',
    '1.1.1.1',
    '172.15.5.5',
    '172.32.0.1',
    '192.167.1.1',
    '11.0.0.1',
    '100.63.1.1',
    '100.128.1.1',
    '169.253.1.1',
    '2001:4860:4860::8888',
    '::ffff:8.8.8.8',
  ])('считает %s публичным', (ip) => {
    expect(isPrivateIp(ip)).toBe(false);
  });
});
